/**
 * Ce que la feuille ajoute a l'arbre des regions.
 *
 * L'arbre garde la main sur tout nom qu'il connait, sous n'importe
 * laquelle de ses ecritures : lui seul porte la region, et reprendre
 * la ville depuis la feuille reviendrait a l'oublier. Ne ressortent
 * donc que les communes qu'il ignore.
 *
 * Le nom leur sert de code : la feuille l'intitule elle-meme
 * CITY_CODE, et c'est bien le nom que Speedaf attend dans le champ
 * ville d'un colis.
 */
export function villesACompleter(
  arbre: CarrierCity[],
  officielles: readonly string[] = VILLES_OFFICIELLES
): CarrierCity[] {
  const connus = new Set(
    arbre.flatMap((v) => [
      ...cityAliases(v.name),
      ...(v.autresNoms ?? []).flatMap((n) => cityAliases(n)),
    ])
  );
  const ajouts: CarrierCity[] = [];
  for (const nom of officielles) {
    const ecritures = cityAliases(nom);
    if (ecritures.some((e) => connus.has(e))) continue;
    // Deux lignes de la feuille peuvent se normaliser pareil : la
    // seconde ferait echouer l'enregistrement du lot entier.
    for (const e of ecritures) connus.add(e);
    ajouts.push({ code: nom, name: nom });
  }
  return ajouts;
}
