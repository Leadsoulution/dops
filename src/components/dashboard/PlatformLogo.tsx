function Glyph({
  path,
  color,
  title,
  size = 15,
}: {
  path: string;
  color: string;
  title: string;
  size?: number;
}) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill={color}
      role="img"
      aria-label={title}
      className="shrink-0"
    >
      <title>{title}</title>
      <path d={path} />
    </svg>
  );
}

/**
 * La plateforme qui a amene la commande. Rien ne s'affiche quand elle
 * est inconnue : une case vide se remarque et se corrige, une icone
 * par defaut ferait passer l'ignorance pour un renseignement.
 */
export function PlatformLogo({ utmSource }: { utmSource?: string }) {
  const platform = adPlatformOf(utmSource);
  if (!platform) return null;
  return (
    <Glyph
      path={PATHS[platform.key]}
      color={platform.color}
      title={platform.label}
    />
  );
}

/** Le nom de la plateforme, pour les infobulles et le detail. */
export function platformLabel(utmSource?: string): string | null {
  return adPlatformOf(utmSource)?.label ?? null;
}

/**
 * La boutique d'ou vient la commande, reduite a son logo.
 *
 * Les sources autres que WooCommerce gardent leur pastille de texte :
 * elles n'ont pas de logo, et un rond gris ne dirait rien.
 */
export function SourceLogo({ source }: { source: string }) {
  if (source !== "WooCommerce") return null;
  return <Glyph path={WOO_PATH} color="#7F54B3" title="WooCommerce" size={20} />;
}

